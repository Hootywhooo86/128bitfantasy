/**
 * PKCE (RFC 7636) for apps with no client secret — Yahoo "Public Client"
 * apps. A random verifier is made per sign-in; its SHA-256 goes out with the
 * sign-in link and the verifier itself goes with the code, proving the same
 * app started and finished the sign-in.
 *
 * SHA-256 is written out here rather than pulled from a native module, so it
 * runs the same on a phone, on the web and in tests.
 */

